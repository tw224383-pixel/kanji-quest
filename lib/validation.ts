async function hashString(str: string): Promise<string> {
  const encoder = new TextEncoder();
  const data = encoder.encode(str);
  const hashBuffer = await crypto.subtle.digest('SHA-256', data);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  const hashHex = hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
  return hashHex;
}

export async function validateName(name: string): Promise<boolean> {
  if (!name) return true;
  
  // スペース、伏せ字によく使われる記号（〇、○、●、*、-、_、.、×、★など）をすべて削除し、小文字に統一
  const normalizedName = name.replace(/[\s　〇○●\*_\-\.\/\\×★☆◆◇■□▲△▼▽]/g, "").toLowerCase();
  
  // 名前から作成できるすべての部分文字列を生成してチェック
  for (let i = 0; i < normalizedName.length; i++) {
    for (let j = i + 1; j <= normalizedName.length; j++) {
      const substring = normalizedName.substring(i, j);
      const hash = await hashString(substring);
      if (NG_HASHES.has(hash)) {
        return false;
      }
    }
  }
  
  return true;
}
